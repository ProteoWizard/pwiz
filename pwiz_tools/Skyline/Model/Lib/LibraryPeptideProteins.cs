using System;
using System.Collections.Generic;
using System.Linq;
using pwiz.CarafeSharp.Proteome;

namespace pwiz.Skyline.Model.Lib
{
    /// <summary>
    /// The protein text of each peptide a predicted library is built for, as Osprey's own FASTA
    /// route labels its peptides (<see cref="LibraryPeptides"/>): a target carries the names of
    /// the document's proteins it is in, joined with <c>;</c> (a FASTA sequence's name is its
    /// header's first token, <c>db|accession|entry</c>); an entrapment peptide generated by
    /// CarafeSharp carries the label CarafeSharp gave it, its own <c>_p_target</c> protein or, placed
    /// in a target protein, that protein's clean label, so a protein-aware scoring step is audited;
    /// a decoy carries its target's labels with CarafeSharp's decoy prefix. A peptide list, an iRT
    /// standard or a peptide of no protein gives none. The library's Proteins table gets these, one
    /// accession per label, beside the DecoyPairs table that flags decoys and entrapment.
    /// </summary>
    public sealed class LibraryPeptideProteins
    {
        /// <summary>The text of a peptide with no protein: nothing, which the writers leave out of the Proteins table.</summary>
        public const string NO_PROTEIN = "";

        private readonly Dictionary<string, string> _proteinsBySequence;

        /// <summary>
        /// Reads <paramref name="document"/>'s proteins, with <paramref name="entrapmentProteinIds"/>
        /// (sequence to label) for the entrapment peptides CarafeSharp generated, which sit in a
        /// peptide list of the document; null for none.
        /// </summary>
        public LibraryPeptideProteins(SrmDocument document, IReadOnlyDictionary<string, string> entrapmentProteinIds)
        {
            _proteinsBySequence = new Dictionary<string, string>(StringComparer.Ordinal);
            var decoys = new List<PeptideDocNode>();
            foreach (var nodeGroup in document.PeptideGroups)
            {
                foreach (var nodePep in nodeGroup.Peptides)
                {
                    if (nodePep.IsDecoy)
                    {
                        decoys.Add(nodePep);
                        continue;
                    }
                    string sequence = nodePep.Target.Sequence;
                    if (entrapmentProteinIds != null && entrapmentProteinIds.TryGetValue(sequence, out string label))
                        Add(sequence, label);
                    else if (nodeGroup.IsProtein)
                        Add(sequence, nodeGroup.Name);
                }
            }
            // The decoys after every target, so a decoy of a target in several proteins gets them all
            foreach (var nodePep in decoys)
            {
                if (_proteinsBySequence.TryGetValue(nodePep.SourceUnmodifiedTarget.Sequence, out string proteins))
                {
                    Add(nodePep.Target.Sequence, string.Join(@";",
                        proteins.Split(';').Select(p => EntrapmentFastaSettings.DEFAULT_DECOY_PREFIX + p)));
                }
            }
        }

        /// <summary>The protein text of <paramref name="nodePep"/>, or <see cref="NO_PROTEIN"/>.</summary>
        public string GetProteinId(PeptideDocNode nodePep)
        {
            return _proteinsBySequence.TryGetValue(nodePep.Target.Sequence, out string proteins) ? proteins : NO_PROTEIN;
        }

        private void Add(string sequence, string proteins)
        {
            if (string.IsNullOrEmpty(proteins))
                return;
            _proteinsBySequence[sequence] = _proteinsBySequence.TryGetValue(sequence, out string existing)
                ? LibraryPeptides.MergeProteins(existing, proteins)
                : proteins;
        }
    }
}
