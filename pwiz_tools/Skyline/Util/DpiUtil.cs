    /// <summary>
    /// Helpers for scaling pixel-based layout to the current display DPI now that
    /// Skyline runs system-DPI-aware (issue #4599). Persisted window geometry follows
    /// the convention "store 96-DPI logical units, scale on restore": values saved by
    /// DPI-unaware builds were logical 96-DPI pixels already, so the convention is
    /// backward compatible with existing user settings.
    /// </summary>
    public static class DpiUtil
    {
        public const int REFERENCE_DPI = DpiScale.REFERENCE_DPI;

        // Embedded per-DPI icons generated by Executables/DevTools/IconBuilder; see GetIcon
        private const int ICON_NATIVE = 16;
        private const int ICON_NATIVE_SMALL = 14;
        private const string ICON_RESOURCE_SUFFIX = ".Resources.Icons.{0}.{1}.png";
        private static readonly int[] ICON_SIZES = { 20, 24, 32 };
        private static readonly int[] ICON_SIZES_SMALL = { 18, 21, 28 };
        private static string[] _iconResourceNames;
        private static readonly Dictionary<int, Dictionary<string, string>> _nativeIconNames =
            new Dictionary<int, Dictionary<string, string>>();

        /// <summary>
        /// Ratio of the control's rendering DPI to the 96 DPI baseline; see
        /// <see cref="DpiScale.Factor"/>. Callers with no control at hand pass null.
        /// </summary>
        public static float GetFactor(Control control)
        {
            return DpiScale.Factor(control);
        }

        public static bool IsScaled(Control control)
        {
            return DpiScale.IsScaled(control);
        }

        /// <summary>
        /// Scales a 96-DPI pixel measurement to the control's rendering DPI.
        /// </summary>
        public static int Scale(Control control, int pixels)
        {
            return DpiScale.Scale(control, pixels);
        }

        /// <summary>
        /// Scales a 96-DPI pixel measurement to the DPI of a Graphics, for paint code that
        /// has no control at hand.
        /// </summary>
        public static int Scale(Graphics g, int pixels)
        {
            return (int)Math.Round(pixels * g.DpiX / REFERENCE_DPI);
        }

        public static Size ScaleSize(Control control, Size size)
        {
            return DpiScale.ScaleSize(control, size);
        }

        /// <summary>
        /// Converts device pixels to the 96-DPI logical units in which window geometry is
        /// persisted (values saved by DPI-unaware builds were logical already, so the
        /// convention is backward compatible with existing settings).
        /// </summary>
        public static Size ScaleToLogical(Control control, Size deviceSize)
        {
            return DpiScale.ToLogical(control, deviceSize);
        }

        public static int ScaleToLogical(Control control, int devicePixels)
        {
            return DpiScale.ToLogical(control, devicePixels);
        }

        /// <summary>
        /// Scales a 96-DPI image to the control's rendering DPI; see <see cref="DpiScale.ScaleImage"/>.
        /// </summary>
        public static Image ScaleImage(Control control, Image image, Color? transparentKey = null)
        {
            return DpiScale.ScaleImage(control, image, transparentKey);
        }

        /// <summary>
        /// Returns an icon at the pixel size the control's DPI calls for. The sizes generated
        /// by Executables/DevTools/IconBuilder are embedded as Resources/Icons/Name.Size.png
        /// (20, 24 and 32 for 16 px icons; 18, 21 and 28 for 14 px ones); the smallest one at
        /// or above the target size is used and resampled down when they differ. With no
        /// embedded file the native bitmap is resampled as <see cref="ScaleImage"/> does.
        /// At 100% the native bitmap is returned untouched; otherwise it is disposed, since
        /// the caller keeps only the result. Pass <c>nameof(Resources.X)</c> as the name.
        /// </summary>
        public static Image GetIcon(Control control, string name, Image native, Color? transparentKey = null)
        {
            if (!IsScaled(control))
                return native;
            var target = ScaleSize(control, native.Size);
            var icon = LoadEmbeddedIcon(name, native.Width, target);
            if (icon == null)
                return DpiScale.ScaleImage(control, native, transparentKey);
            native.Dispose();
            return icon;
        }

        /// <summary>
        /// The pre-rendered pixel sizes IconBuilder emits for a native icon size, in
        /// ascending order: 125%, 150% and 200%.
        /// </summary>
        public static int[] GetIconSizes(int nativeSize)
        {
            return nativeSize == ICON_NATIVE_SMALL ? ICON_SIZES_SMALL : ICON_SIZES;
        }

        /// <summary>
        /// The manifest resource name of an embedded icon file, or null when none is embedded.
        /// Matched by suffix so the root namespace never has to be spelled out here.
        /// </summary>
        public static string GetIconResourceName(string name, int size)
        {
            var suffix = string.Format(CultureInfo.InvariantCulture, ICON_RESOURCE_SUFFIX, name, size);
            return IconResourceNames.FirstOrDefault(n => n.EndsWith(suffix, StringComparison.Ordinal));
        }

        /// <summary>
        /// Routes the designer images under a control through <see cref="GetIcon"/>: the items
        /// of its tool strips, menus and context menus, and the images of its buttons and
        /// picture boxes. Designers assign Resources.X directly and an Image carries no
        /// resource name, so each image is matched by pixel content against the small bitmaps
        /// of Resources.resx (see <see cref="GetIconName"/>). A button's ImageList is scaled as
        /// a whole; an image shared by several controls is replaced once and shared again.
        /// Called when a form loads; a context menu that is not attached to a control, or a
        /// control created later, goes through <see cref="PrepareIcons(ToolStrip)"/> or this
        /// method itself. No-op at 100%, where the natives are right as they are.
        /// </summary>
        public static void PrepareIcons(Control root)
        {
            if (!IsScaled(root))
                return;
            var replaced = new Dictionary<Image, Image>();
            var scaledLists = new HashSet<ImageList>();
            var pending = new Stack<Control>();
            pending.Push(root);
            while (pending.Count > 0)
            {
                var control = pending.Pop();
                foreach (Control child in control.Controls)
                    pending.Push(child);
                if (control.ContextMenuStrip != null)
                    PrepareIcons(control.ContextMenuStrip.Items, control, replaced);
                if (control is ToolStrip strip)
                    PrepareIcons(strip.Items, strip, replaced);
                else if (control is PictureBox pictureBox)
                    pictureBox.Image = ReplaceIcon(pictureBox, pictureBox.Image, replaced, false);
                else if (control.GetType() == typeof(Button))
                {
                    // Exact type only: Button subclasses (e.g. LiteDropDownList) manage their own images.
                    // WinForms leaves a Button's Image at its 96-DPI size, so an unmatched one is resampled.
                    var button = (Button) control;
                    if (button.ImageList == null)
                        button.Image = ReplaceIcon(button, button.Image, replaced, true);
                    else if (scaledLists.Add(button.ImageList))
                        ImageListScaler.ScaleToDpi(button, button.ImageList);
                }
            }
        }

        /// <summary>
        /// <see cref="PrepareIcons(Control)"/> for a tool strip or context menu that no form's
        /// control tree reaches, e.g. a menu a component shows on its own.
        /// </summary>
        public static void PrepareIcons(ToolStrip strip)
        {
            if (IsScaled(strip))
                PrepareIcons(strip.Items, strip, new Dictionary<Image, Image>());
        }

        /// <summary>
        /// The Resources.resx name of a small icon bitmap, matched by pixel content, or null
        /// for an image that is not one (a designer image carries no name). The transparent
        /// key is the one the image's owner applied to it: a ToolStripItem makes its
        /// ImageTransparentColor transparent in the bitmap it is given, so the natives are
        /// keyed the same way before they are compared. Two names with the same pixels
        /// resolve to the first in ordinal order.
        /// </summary>
        public static string GetIconName(Image image, Color transparentKey = default)
        {
            if (image.Width > ICON_NATIVE || image.Height > ICON_NATIVE)
                return null;
            var names = GetNativeIconNames(transparentKey);
            return names.TryGetValue(GetPixelKey(image, Color.Empty), out var name) ? name : null;
        }

        private static string[] IconResourceNames
        {
            get { return _iconResourceNames ??= typeof(DpiUtil).Assembly.GetManifestResourceNames(); }
        }

        private static void PrepareIcons(ToolStripItemCollection items, Control control,
            Dictionary<Image, Image> replaced)
        {
            foreach (ToolStripItem item in items)
            {
                if (item is ToolStripDropDownItem dropDown)
                    PrepareIcons(dropDown.DropDownItems, control, replaced);
                // An item drawn from its strip's ImageList by index or key is left to the list
                if (item.ImageIndex >= 0 || !string.IsNullOrEmpty(item.ImageKey))
                    continue;
                item.Image = ReplaceIcon(control, item.Image, replaced, false, item.ImageTransparentColor);
            }
        }

        /// <summary>
        /// The image to show for a 96-DPI designer image at the control's DPI: the result of
        /// <see cref="GetIcon"/> for a Resources.resx icon, the bicubic resample for anything
        /// else when asked for, otherwise the image itself.
        /// </summary>
        private static Image ReplaceIcon(Control control, Image image, Dictionary<Image, Image> replaced,
            bool resampleUnknown, Color transparentKey = default)
        {
            if (image == null)
                return null;
            if (replaced.TryGetValue(image, out var result))
                return result;
            var name = GetIconName(image, transparentKey);
            if (name != null)
                result = GetIcon(control, name, image);
            else if (resampleUnknown)
                result = ScaleImage(control, image);
            else
                result = image;
            replaced.Add(image, result);
            return result;
        }

        /// <summary>
        /// Pixel-content key to Resources.resx name for every bitmap up to 16 px, with the
        /// given transparent key applied, built on first use per key color. Enumerating the
        /// resource set deserializes a fresh bitmap per entry (objects are not cached the way
        /// strings are), so each one is disposed once keyed.
        /// </summary>
        private static Dictionary<string, string> GetNativeIconNames(Color transparentKey)
        {
            if (_nativeIconNames.TryGetValue(transparentKey.ToArgb(), out var names))
                return names;
            names = new Dictionary<string, string>();
            var resourceSet = Resources.ResourceManager.GetResourceSet(CultureInfo.InvariantCulture, true, true);
            foreach (DictionaryEntry entry in resourceSet)
            {
                if (!(entry.Value is Bitmap bitmap))
                    continue;
                using (bitmap)
                {
                    if (bitmap.Width > ICON_NATIVE || bitmap.Height > ICON_NATIVE)
                        continue;
                    var key = GetPixelKey(bitmap, transparentKey);
                    var name = (string) entry.Key;
                    if (!names.TryGetValue(key, out var existing) || string.CompareOrdinal(name, existing) < 0)
                        names[key] = name;
                }
            }
            _nativeIconNames[transparentKey.ToArgb()] = names;
            return names;
        }

        /// <summary>
        /// The image's size and 32-bit ARGB pixels as a string, after the transparent key
        /// (if any) is made transparent the way ToolStripItem does it, so bitmaps decoded
        /// from the same resource bytes compare equal whatever their pixel format. Every
        /// fully transparent pixel reads as zero, whatever color it carries.
        /// </summary>
        private static string GetPixelKey(Image image, Color transparentKey)
        {
            using (var bitmap = new Bitmap(image.Width, image.Height, PixelFormat.Format32bppArgb))
            {
                using (var g = Graphics.FromImage(bitmap))
                {
                    g.CompositingMode = CompositingMode.SourceCopy;
                    g.DrawImage(image, new Rectangle(Point.Empty, image.Size),
                        new Rectangle(Point.Empty, image.Size), GraphicsUnit.Pixel);
                }
                if (transparentKey != Color.Empty)
                    bitmap.MakeTransparent(transparentKey);
                var data = bitmap.LockBits(new Rectangle(Point.Empty, bitmap.Size), ImageLockMode.ReadOnly,
                    PixelFormat.Format32bppArgb);
                try
                {
                    var bytes = new byte[data.Stride * data.Height];
                    Marshal.Copy(data.Scan0, bytes, 0, bytes.Length);
                    for (var i = 0; i < bytes.Length; i += 4)
                    {
                        if (bytes[i + 3] == 0)   // B, G, R, A
                            bytes[i] = bytes[i + 1] = bytes[i + 2] = 0;
                    }
                    return string.Format(CultureInfo.InvariantCulture, @"{0}x{1}:{2}",
                        image.Width, image.Height, Convert.ToBase64String(bytes));
                }
                finally
                {
                    bitmap.UnlockBits(data);
                }
            }
        }

        private static Image LoadEmbeddedIcon(string name, int nativeSize, Size target)
        {
            // Smallest pre-rendered size at or above the target, else the largest there is
            var sizes = GetIconSizes(nativeSize);
            var size = sizes.FirstOrDefault(s => s >= target.Width);
            if (size == 0)
                size = sizes.Last();
            var resourceName = GetIconResourceName(name, size);
            if (resourceName == null)
                return null;
            using (var stream = typeof(DpiUtil).Assembly.GetManifestResourceStream(resourceName))
            using (var loaded = new Bitmap(stream))
            {
                if (loaded.Size == target)
                    return CopyBitmap(loaded);
                return DpiScale.Resample(loaded, target);
            }
        }

        /// <summary>
        /// Pixel-exact copy into a 96-DPI 32-bit ARGB bitmap that does not depend on the
        /// stream the original was decoded from.
        /// </summary>
        private static Bitmap CopyBitmap(Bitmap source)
        {
            var copy = new Bitmap(source.Width, source.Height, PixelFormat.Format32bppArgb);
            copy.SetResolution(REFERENCE_DPI, REFERENCE_DPI);
            using (var g = Graphics.FromImage(copy))
            {
                g.DrawImage(source, new Rectangle(Point.Empty, source.Size), new Rectangle(Point.Empty, source.Size), GraphicsUnit.Pixel);
            }
            return copy;
        }

        /// <summary>
        /// Draws an image at its own pixel size, vertically centered in a row, into an
        /// explicit destination rectangle. DrawImageUnscaled honors the image's DPI
        /// metadata and would re-inflate bitmaps created in a high-DPI process, so
        /// owner-drawn lists and trees share this instead (issue #4599).
        /// </summary>
        public static void DrawImageCentered(Graphics g, Image image, int x, int rowTop, int rowHeight)
        {
            g.DrawImage(image, new Rectangle(x, rowTop + (rowHeight - image.Height) / 2,
                image.Width, image.Height));
        }

        /// <summary>
        /// Fills a TabPage with a control from its designer position to the page's bottom
        /// edge and to the given right margin (device pixels), on every resize. On .NET a
        /// control anchored to the bottom of a TabPage comes out short at high DPI, and the
        /// Dock.Fill-with-Padding workaround shifts the page's other anchored controls by
        /// the padding (WinForms anchors them to the padded display rectangle), so the
        /// control is sized by hand instead. The right margin is a parameter because the
        /// control's own width cannot be trusted either (a ZedGraphControl measured 422
        /// wide on a 1059-wide page) (issue #4599).
        /// </summary>
        public static void FillTabPage(TabPage page, Control control, int right)
        {
            int left = control.Left, top = control.Top;
            control.Anchor = AnchorStyles.None;
            page.Resize += (sender, args) => FitTabPage(page, control, left, top, right);
            FitTabPage(page, control, left, top, right);
        }

        private static void FitTabPage(TabPage page, Control control, int left, int top, int right)
        {
            control.Bounds = new Rectangle(left, top, page.ClientSize.Width - left - right, page.ClientSize.Height - top);
        }

        /// <summary>
        /// Keeps the designer's bottom anchors on tab-page controls from misplacing them at
        /// high DPI on .NET, where WinForms sizes a TabPage only after its children are
        /// scaled. The anchors are held from the top until the form has loaded and the
        /// pages have their final size, then restored as designed, so the resx keeps the
        /// anchors the designer shows (issue #4599).
        /// </summary>
        public static void DeferBottomAnchors(Form form, params TabPage[] pages)
        {
            var deferred = new List<KeyValuePair<Control, AnchorStyles>>();
            foreach (var page in pages)
            {
                foreach (Control control in page.Controls)
                {
                    if ((control.Anchor & AnchorStyles.Bottom) == 0)
                        continue;
                    deferred.Add(new KeyValuePair<Control, AnchorStyles>(control, control.Anchor));
                    control.Anchor = (control.Anchor & ~AnchorStyles.Bottom) | AnchorStyles.Top;
                }
            }
            form.Load += (sender, args) =>
            {
                foreach (var entry in deferred)
                    entry.Key.Anchor = entry.Value;
            };
        }

        /// <summary>
        /// Rewrites a freshly saved docking-layout (.view) file so floating-window SIZES
        /// are stored in 96-DPI logical units, keeping the file portable across machines
        /// with different display scaling (files saved by DPI-unaware builds are logical
        /// by definition, so the convention is backward compatible and old Skyline
        /// versions can read new files unchanged). Positions stay in physical screen
        /// coordinates - where the user put the window on THEIR screen - and off-screen
        /// cases are handled by EnsureFloatingWindowsVisible on load. The docked layout
        /// is stored as fractions by DigitalRune and needs no treatment. No-op at 100%.
        /// </summary>
        public static void NormalizeDockLayoutFile(Control control, string path)
        {
            if (!IsScaled(control))
                return;
            var factor = GetFactor(control);
            byte[] transformed;
            try
            {
                var doc = XDocument.Load(path);
                if (!ScaleFloatingWindowSizes(doc, 1 / factor))
                    return;
                // Serialize completely in memory first: a failure part-way through must not
                // leave a truncated file where the caller is about to commit it.
                var stream = new MemoryStream();
                using (var writer = XmlWriter.Create(stream,
                           new XmlWriterSettings { Encoding = new UTF8Encoding(false), Indent = true, CloseOutput = false }))
                {
                    doc.Save(writer);
                }
                transformed = stream.ToArray();
            }
            catch (Exception)
            {
                // A layout that cannot be transformed is saved in device pixels - degraded
                // but functional, and preferable to failing the document save.
                return;
            }
            // Outside the fallback on purpose: a failed write can leave the file truncated,
            // and the error must reach the caller so its FileSaver discards the file instead
            // of committing it over the user's layout.
            File.WriteAllBytes(path, transformed);
        }

        /// <summary>
        /// Stream form of <see cref="NormalizeDockLayoutFile"/>, for a layout captured
        /// with DockPanel.SaveAsXml that will later be reloaded through
        /// <see cref="DenormalizeDockLayoutStream"/>. Returns the original stream untouched
        /// at 100% scaling or if the stream cannot be transformed.
        /// </summary>
        public static Stream NormalizeDockLayoutStream(Control control, Stream layoutStream)
        {
            return IsScaled(control) ? TransformDockLayoutStream(layoutStream, 1 / GetFactor(control)) : layoutStream;
        }

        /// <summary>
        /// Counterpart of <see cref="NormalizeDockLayoutFile"/>: scales floating-window
        /// sizes in a docking-layout stream from 96-DPI logical units to the current
        /// display DPI before DigitalRune parses it. Returns the original stream untouched
        /// at 100% scaling or if the stream cannot be transformed.
        /// </summary>
        public static Stream DenormalizeDockLayoutStream(Control control, Stream layoutStream)
        {
            return IsScaled(control) ? TransformDockLayoutStream(layoutStream, GetFactor(control)) : layoutStream;
        }

        private static Stream TransformDockLayoutStream(Stream layoutStream, float factor)
        {
            var startPosition = layoutStream.CanSeek ? layoutStream.Position : 0;
            try
            {
                var doc = XDocument.Load(layoutStream);
                var transformed = new MemoryStream();
                using (var writer = XmlWriter.Create(transformed,
                           new XmlWriterSettings { Encoding = new UTF8Encoding(false), CloseOutput = false }))
                {
                    ScaleFloatingWindowSizes(doc, factor);
                    doc.Save(writer);
                }
                transformed.Position = 0;
                return transformed;
            }
            catch (Exception)
            {
                if (layoutStream.CanSeek)
                    layoutStream.Position = startPosition;
                return layoutStream;
            }
        }

        /// <summary>
        /// Multiplies the width and height components of every FloatingWindow Bounds
        /// attribute ("x, y, w, h") by the factor. Returns true if anything changed.
        /// </summary>
        private static bool ScaleFloatingWindowSizes(XDocument doc, float factor)
        {
            var anyChanged = false;
            foreach (var boundsAttr in doc.Descendants(@"FloatingWindow")
                         .Select(fw => fw.Attribute(@"Bounds")).Where(attr => attr != null))
            {
                var parts = boundsAttr.Value.Split(',');
                if (parts.Length != 4)
                    continue;
                var values = new int[4];
                var parsed = true;
                for (var i = 0; i < 4; i++)
                    parsed = parsed && int.TryParse(parts[i].Trim(), NumberStyles.Integer,
                        CultureInfo.InvariantCulture, out values[i]);
                if (!parsed)
                    continue;
                values[2] = (int)Math.Round(values[2] * factor);
                values[3] = (int)Math.Round(values[3] * factor);
                boundsAttr.Value = string.Join(@", ",
                    values.Select(v => v.ToString(CultureInfo.InvariantCulture)));
                anyChanged = true;
            }
            return anyChanged;
        }
    }
