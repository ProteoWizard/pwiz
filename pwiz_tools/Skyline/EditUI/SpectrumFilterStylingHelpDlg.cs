using System;
using System.Collections.Generic;
using System.Linq;
using System.Drawing;
using System.Windows.Forms;
using pwiz.Skyline.Model.Results.Spectra;
using pwiz.Skyline.Util;

namespace pwiz.Skyline.EditUI
{
    /// <summary>
    /// Explains how the spectrum filter editor styles its property list, by showing each style rather than
    /// naming it: a sample is drawn exactly as the list draws it, above the sentence saying what it means.
    /// Naming a color is no help to a reader who cannot tell which entries have it, and the accent comes
    /// from the system scheme, so its name is not something this text could state anyway.
    ///
    /// Built in code rather than from a designer: the whole form is a styled block of text whose styling
    /// has to be applied at run time from <see cref="SystemColors"/>, so there is nothing a designer would
    /// own.
    /// </summary>
    public class SpectrumFilterStylingHelpDlg : FormEx
    {
        private readonly RichTextBox _richTextBox;
        private Font _regularFont;
        private Font _italicFont;

        public SpectrumFilterStylingHelpDlg()
        {
            Text = EditUIResources.SpectrumFilterStylingHelpDlg_Title_Property_styling;
            FormBorderStyle = FormBorderStyle.FixedDialog;
            MaximizeBox = false;
            MinimizeBox = false;
            ShowInTaskbar = false;
            StartPosition = FormStartPosition.CenterParent;
            ClientSize = new Size(500, 320);

            _richTextBox = new RichTextBox
            {
                Dock = DockStyle.Fill,
                BorderStyle = BorderStyle.None,
                ReadOnly = true,
                TabStop = false,
                BackColor = SystemColors.Control,
                Margin = new Padding(12)
            };
            var panel = new Panel { Dock = DockStyle.Fill, Padding = new Padding(12, 12, 12, 0) };
            panel.Controls.Add(_richTextBox);

            // Laid out by the flow panel rather than by coordinates: a position computed from the client
            // size is only right at the scaling this was written at, and lands somewhere arbitrary - or off
            // the form - once the display scales it.
            var buttonPanel = new FlowLayoutPanel
            {
                Dock = DockStyle.Bottom,
                FlowDirection = FlowDirection.RightToLeft,
                Padding = new Padding(12),
                AutoSize = true,
                AutoSizeMode = AutoSizeMode.GrowAndShrink
            };
            var btnOk = new Button
            {
                Text = EditUIResources.SpectrumFilterStylingHelpDlg_Ok,
                DialogResult = DialogResult.OK,
                AutoSize = true,
                AutoSizeMode = AutoSizeMode.GrowAndShrink,
                MinimumSize = new Size(75, 23)
            };
            buttonPanel.Controls.Add(btnOk);

            Controls.Add(panel);
            Controls.Add(buttonPanel);
            AcceptButton = btnOk;
            CancelButton = btnOk;

            // Leaves no caret blinking in what is only a block of text to read.
            _richTextBox.GotFocus += (sender, args) => btnOk.Focus();
        }

        /// <summary>
        /// The content is written here rather than in the constructor because a RichTextBox ignores
        /// SelectionColor and SelectionFont until its window handle exists - the styling would simply not
        /// appear, with nothing to indicate it had been asked for.
        /// </summary>
        protected override void OnLoad(EventArgs e)
        {
            base.OnLoad(e);
            BuildContent(_richTextBox);
        }

        /// <summary>
        /// Writes what a spectrum filter is, then the styling key - each style shown in itself, so the
        /// reader matches what they see in the list against what they see here rather than against a word
        /// for it. The styles come from <see cref="SpectrumColumnStyle"/>, the same source the list draws
        /// from, and the key is generated by walking the states rather than listing them, so a state added
        /// later cannot quietly go undescribed.
        /// </summary>
        private void BuildContent(RichTextBox richTextBox)
        {
            _regularFont = new Font(richTextBox.Font, FontStyle.Regular);
            _italicFont = new Font(richTextBox.Font, FontStyle.Italic);

            AppendRun(richTextBox, EditUIResources.SpectrumFilterStylingHelpDlg_What_is_a_spectrum_filter,
                SystemColors.WindowText, _regularFont);
            AppendRun(richTextBox, Environment.NewLine + Environment.NewLine + Environment.NewLine,
                SystemColors.WindowText, _regularFont);
            AppendRun(richTextBox, EditUIResources.SpectrumFilterStylingHelpDlg_Styling_intro,
                SystemColors.WindowText, _regularFont);
            AppendRun(richTextBox, Environment.NewLine, SystemColors.WindowText, _regularFont);

            foreach (var standing in GetDisplayOrder())
            {
                AppendRun(richTextBox, Environment.NewLine, SystemColors.WindowText, _regularFont);
                // The style's own name, written in that style: the point is to be recognized, not read.
                AppendRun(richTextBox, GetStyleName(standing),
                    SpectrumColumnStyle.GetForeColor(standing, SystemColors.WindowText),
                    SpectrumColumnStyle.GetFontStyle(standing) == FontStyle.Italic ? _italicFont : _regularFont);
                AppendRun(richTextBox, GetExplanation(standing), SystemColors.WindowText, _regularFont);
            }

            richTextBox.Select(0, 0);
        }

        /// <summary>
        /// The states in the order they are described: the two that say something about the data first,
        /// then the one that says nothing. Any state missing from this list is still described, appended at
        /// the end, so adding one cannot leave it silently out of the key.
        /// </summary>
        private static IEnumerable<SpectrumColumnScanner.Standing> GetDisplayOrder()
        {
            var ordered = new[]
            {
                SpectrumColumnScanner.Standing.answerable,
                SpectrumColumnScanner.Standing.unanswerable,
                SpectrumColumnScanner.Standing.undetermined
            };
            return ordered.Concat(Enum.GetValues(typeof(SpectrumColumnScanner.Standing))
                .Cast<SpectrumColumnScanner.Standing>().Where(standing => !ordered.Contains(standing)));
        }

        private static string GetStyleName(SpectrumColumnScanner.Standing standing)
        {
            switch (standing)
            {
                case SpectrumColumnScanner.Standing.answerable:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Style_name_accent_color;
                case SpectrumColumnScanner.Standing.unanswerable:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Style_name_italic;
                default:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Style_name_plain;
            }
        }

        private static string GetExplanation(SpectrumColumnScanner.Standing standing)
        {
            switch (standing)
            {
                case SpectrumColumnScanner.Standing.answerable:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Explains_answerable;
                case SpectrumColumnScanner.Standing.unanswerable:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Explains_unanswerable;
                default:
                    return EditUIResources.SpectrumFilterStylingHelpDlg_Explains_undetermined;
            }
        }

        private static void AppendRun(RichTextBox richTextBox, string text, Color color, Font font)
        {
            richTextBox.SelectionStart = richTextBox.TextLength;
            richTextBox.SelectionLength = 0;
            richTextBox.SelectionColor = color;
            richTextBox.SelectionFont = font;
            richTextBox.AppendText(text);
        }

        protected override void OnFormClosed(FormClosedEventArgs e)
        {
            _regularFont?.Dispose();
            _italicFont?.Dispose();
            _regularFont = null;
            _italicFont = null;
            base.OnFormClosed(e);
        }
    }
}
