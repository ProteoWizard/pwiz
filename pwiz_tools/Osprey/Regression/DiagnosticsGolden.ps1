<#
.SYNOPSIS
    Model-diagnostics spot-check capture + comparison for the Osprey regression
    harness.

.DESCRIPTION
    Dot-source this file to get the diagnostics-report metric projection and the
    capture / compare functions used by regression.ps1 for datasets whose spec
    sets ModelDiagnostics.

    The blib golden proves the SEARCH did not change. This proves the FDR
    CALIBRATION did not change, and -- more importantly -- that it is still
    correct. Those are different questions: a change can leave the ranking
    intact and still wreck q-value calibration (that is exactly what the b<->y
    decoy swap did, at ~12x the reported error rate).

    TWO TIERS, deliberately:

      1. GOLDEN-EXACT (Compare-DiagnosticsGolden). Every metric compared to the
         committed golden at 1e-9. The pipeline is deterministic, so any drift
         is a real change. Regenerated by regression.ps1 -CreateGolden, like
         every other golden.

      2. SANITY BOUNDS (Test-DiagnosticsSanity). Committed IN THIS SCRIPT and
         NOT regenerated by -CreateGolden. A golden rebaseline is precisely how
         a bad change gets blessed into the baseline -- the golden happily
         records whatever the run produced. These bounds are the only thing that
         fails when that happens, so they must not be derived from the run.

.NOTES
    READING THE REPORT -- two traps, both already paid for once:

    * The payload is ONE JSON blob (ModelDiagnosticsHtml substitutes it at the
      /*__OSPREY_DATA__*/ token inside a <script type="application/json">).
      Top-level fdpViews is PASS 1; the nested pass2.fdpViews is PASS 2. Because
      the Pass2 property serializes BEFORE the top-level array, a raw text scan
      for the first "fdpViews" returns Pass 2 while looking like Pass 1 -- which
      inverted a whole session's conclusions once. This script selects on the
      explicit view.pass field, which is unambiguous regardless of ordering.

    * FdpView holds PARALLEL ARRAYS (q / combined / paired / nTargetAccepted),
      not an array of point objects. Asking for .points yields $null, and
      $null.Count is 0 in PowerShell -- i.e. "no data" is indistinguishable from
      a typo. Index the arrays.

    The 1% pick is the LAST grid point with q <= 0.01, not the first point at or
    above it. That is both correct FDR semantics (accept everything at or below
    the threshold) and the convention every recorded measurement in
    ai/todos/.../TODO-20260725_osprey_gendecoy_salvage_or_deadend.md used;
    picking the other neighbour shifts Astral's recorded 2.03% to 2.07% and its
    accepted count by ~300, silently making new numbers non-comparable to the
    investigation they are meant to protect.
#>

$ErrorActionPreference = 'Stop'

# The TSV layer (Write-Tsv / Read-Tsv / Format-CellValue) is BlibGolden's, reused
# rather than reimplemented: a second copy drifted on both of the things a golden
# comparator must not get wrong -- it wrote through Set-Content -Encoding UTF8
# (a BOM under Windows PowerShell 5.1) and parsed with the CURRENT culture, so a
# de-DE agent read the invariant "1.5" it had just written as 15. Dot-sourced here
# rather than relying on regression.ps1 to have done it first, so this file works
# standalone and cannot depend on load order.
. (Join-Path $PSScriptRoot 'BlibGolden.ps1')

# Reported-q threshold the spot checks are quoted at.
$script:DiagQThreshold = 0.01

# Emitted for a metric that does not apply to this dataset (e.g. every
# entrapment metric on a gendecoy dataset with no entrapment peptides). Kept as
# an explicit row rather than an omitted one so the golden's shape is stable and
# a dataset that gains or loses entrapment shows up as a diff instead of a
# silently shorter file.
$script:DiagNotApplicable = 'n/a'

function Get-DiagnosticsPayload {
    <#
    Parse the single JSON payload out of a model-diagnostics HTML report.
    #>
    param([Parameter(Mandatory = $true)][string]$HtmlPath)

    if (-not (Test-Path $HtmlPath)) { throw "Model-diagnostics report not found: $HtmlPath" }
    $text = Get-Content $HtmlPath -Raw
    if ($text -notmatch '(?s)<script[^>]*type="application/json"[^>]*>(.*?)</script>') {
        throw "No application/json payload in $HtmlPath (report format changed?)"
    }
    return ($Matches[1].Trim() | ConvertFrom-Json)
}

function Get-FdpAtThreshold {
    <#
    The FDP view's values at the reported-q threshold: the LAST index whose q is
    <= the threshold. Returns $null when the view is absent or carries no points
    (a dataset without entrapment has no FDP curve at all).
    #>
    param([Parameter(Mandatory = $true)]$Payload, [int]$Pass, [string]$Scope,
          [double]$Threshold = $script:DiagQThreshold)

    $views = if ($Pass -eq 2) { $Payload.pass2.fdpViews } else { $Payload.fdpViews }
    if ($null -eq $views) { return $null }
    $view = $views | Where-Object { $_.pass -eq $Pass -and $_.scope -eq $Scope } | Select-Object -First 1
    if ($null -eq $view -or $null -eq $view.q -or $view.q.Count -eq 0) { return $null }

    $idx = -1
    for ($i = 0; $i -lt $view.q.Count; $i++) {
        if ($view.q[$i] -le $Threshold) { $idx = $i } else { break }
    }
    if ($idx -lt 0) { return $null }

    return [pscustomobject]@{
        Q               = $view.q[$idx]
        Combined        = $view.combined[$idx]
        # Paired is null when no pairing manifest was supplied, and deliberately
        # suppressed when the entrapment library is not ~1:1 (the paired
        # estimator is only valid at r = 1).
        Paired          = if ($null -ne $view.paired) { $view.paired[$idx] } else { $null }
        Accepted        = $view.nTargetAccepted[$idx]
        EntrapmentRatio = $view.entrapmentRatio
    }
}

function Get-DiagnosticsMetrics {
    <#
    The ordered metric projection captured for a dataset. Returns rows of
    (metric, value) with values already rendered as round-trippable strings.
    #>
    param([Parameter(Mandatory = $true)][string]$HtmlPath)

    $d = Get-DiagnosticsPayload -HtmlPath $HtmlPath
    $rows = [System.Collections.Generic.List[object[]]]::new()

    function Add-Metric([string]$name, $value) {
        if ($null -eq $value) {
            $rows.Add(@($name, $script:DiagNotApplicable))
        } elseif ($value -is [double] -or $value -is [float]) {
            $rows.Add(@($name, ([double]$value).ToString('R', [System.Globalization.CultureInfo]::InvariantCulture)))
        } else {
            $rows.Add(@($name, [string]$value))
        }
    }

    # --- Pool composition (entrapment-independent) -------------------------
    Add-Metric 'hasEntrapment' ([string]$d.hasEntrapment)
    Add-Metric 'nTarget'       $d.nTarget
    Add-Metric 'nDecoy'        $d.nDecoy
    Add-Metric 'fileCount'     $d.fileCount
    Add-Metric 'featureCount'  $d.featureCount

    # --- Null-alignment density ratio (needs decoys only) ------------------
    # flatnessSlope is the target:decoy tilt; refFlatnessSlope is the matched
    # entrapment null and exists only with entrapment.
    Add-Metric 'densityRatio.flatnessSlope'    $d.densityRatio.flatnessSlope
    Add-Metric 'densityRatio.plateauRatio'     $d.densityRatio.plateauRatio
    Add-Metric 'densityRatio.nullRegionLo'     $d.densityRatio.nullRegionLo
    Add-Metric 'densityRatio.nullRegionHi'     $d.densityRatio.nullRegionHi
    Add-Metric 'densityRatio.nullRegionBins'   $d.densityRatio.nullRegionBins
    Add-Metric 'densityRatio.refFlatnessSlope' $(if ($d.densityRatio.hasEntrapment) { $d.densityRatio.refFlatnessSlope } else { $null })

    # --- Paired decoy-win fraction (the coin) ------------------------------
    # A fair null sits at 0.5. The real coin needs only decoys; the entrapment
    # coin is the decoy-independent one and needs entrapment.
    Add-Metric 'winFraction.nullBandReal' $d.winFraction.nullBandReal
    Add-Metric 'winFraction.nullBandEnt'  $(if ($d.winFraction.hasEntrapment) { $d.winFraction.nullBandEnt } else { $null })

    # --- Peak co-assignment (issue #4522) ----------------------------------
    # Pinned at BOTH passes and BOTH q scopes. Without these the panel ships with no golden
    # coverage at all: this projection is an explicit metric list, not an enumeration of the
    # payload, so a new card is invisible to the comparison until it is named here. The counts
    # are the critical ones (nBetter is the "would go away under best-match-wins" number);
    # the fractions follow from them and n, so pinning both would only double the failure noise.
    foreach ($p in 1, 2) {
        $ca = if ($p -eq 2) { $d.pass2.coAssignment } else { $d.coAssignment }
        foreach ($scope in 'run', 'experiment') {
            $s = if ($ca) { $ca.$scope } else { $null }
            foreach ($cls in 'target', 'entrapment', 'decoy') {
                $r = if ($s) { $s.$cls } else { $null }
                Add-Metric "pass$p.coAssign.$scope.$cls.n"       $(if ($r) { $r.n } else { $null })
                Add-Metric "pass$p.coAssign.$scope.$cls.nBetter" $(if ($r) { $r.nBetter } else { $null })
            }
            # NaN when a class is under MIN_N_FOR_ENRICHMENT, which is itself worth pinning: it
            # says the run had too few of that class to make a ratio, and a change in that is a
            # change in the pool.
            Add-Metric "pass$p.coAssign.$scope.enrichment" $(if ($s) { $s.enrichment } else { $null })
        }
        # The acceptance boundary in use, and the score this pass's OWN population needs to reach
        # the target FDR. Pinned because their divergence is the pool-selection signal: they agree
        # at pass 1 and separate at pass 2 when compaction has stripped the winning decoys, and a
        # change in that separation is a change in how the second pass is built. The counts are
        # pinned beside the score so a drift shows whether it moved the IDs, the decoys, or both.
        Add-Metric "pass$p.coAssign.cutoff"             $(if ($ca) { $ca.experimentCutoff } else { $null })
        Add-Metric "pass$p.coAssign.fdrCrossing"        $(if ($ca) { $ca.experimentFdrCrossing } else { $null })
        Add-Metric "pass$p.coAssign.fdrCrossingDecoys"  $(if ($ca) { $ca.experimentFdrCrossingDecoys } else { $null })
        Add-Metric "pass$p.coAssign.fdrCrossingNonDecoys" $(if ($ca) { $ca.experimentFdrCrossingNonDecoys } else { $null })
    }

    # --- FDP at the reported-q threshold (entrapment only) -----------------
    foreach ($pass in 1, 2) {
        $fdp = Get-FdpAtThreshold -Payload $d -Pass $pass -Scope 'experiment'
        Add-Metric "pass$pass.experiment.reportedQ"       $(if ($fdp) { $fdp.Q } else { $null })
        Add-Metric "pass$pass.experiment.combinedFdp"     $(if ($fdp) { $fdp.Combined } else { $null })
        Add-Metric "pass$pass.experiment.pairedFdp"       $(if ($fdp) { $fdp.Paired } else { $null })
        Add-Metric "pass$pass.experiment.accepted"        $(if ($fdp) { $fdp.Accepted } else { $null })
        Add-Metric "pass$pass.experiment.entrapmentRatio" $(if ($fdp) { $fdp.EntrapmentRatio } else { $null })
    }

    return [pscustomobject]@{ Header = @('metric', 'value'); Rows = $rows }
}

function Save-DiagnosticsGolden {
    <#
    Capture diagnostics.tsv for a run's model-diagnostics report into GoldenDir.
    #>
    param([Parameter(Mandatory = $true)][string]$HtmlPath,
          [Parameter(Mandatory = $true)][string]$GoldenDir)

    New-Item -ItemType Directory -Path $GoldenDir -Force | Out-Null
    $proj = Get-DiagnosticsMetrics -HtmlPath $HtmlPath
    Write-Tsv -Path (Join-Path $GoldenDir 'diagnostics.tsv') -Header $proj.Header -Rows $proj.Rows
}

function Compare-DiagnosticsGolden {
    <#
    Tier 1: compare a fresh report's metrics against the committed golden.
    Numeric metrics at absolute Tolerance; everything else exact. Returns
    Pass + Issues.

    -NoTrainedModel is for a report emitted by a run that ADOPTED first-pass
    q-values from the .1st-pass.fdr_scores.bin sidecars instead of training
    Percolator (FirstPassFdrTask.Rehydrate -- regression.ps1 mode 5). Exactly one
    metric is model-derived: featureCount comes from the FeatureContributions
    the trainer produces, and a run that never trained has none to report. The
    switch does NOT skip that metric -- it PINS it at 0, so the comparison stays
    total: every metric is still asserted, one of them against the value a
    modelless run must have rather than against the golden. Skipping instead
    would leave the report free to lose its feature view on the straight-through
    path too, unnoticed.
    #>
    param([Parameter(Mandatory = $true)][string]$HtmlPath,
          [Parameter(Mandatory = $true)][string]$GoldenDir,
          [double]$Tolerance = 1e-9,
          [switch]$NoTrainedModel)

    $issues = [System.Collections.Generic.List[string]]::new()
    # The one model-derived metric, named once so the two places below that treat
    # it specially cannot drift apart.
    $modelMetric = 'featureCount'
    $goldenPath = Join-Path $GoldenDir 'diagnostics.tsv'
    if (-not (Test-Path $goldenPath)) {
        $issues.Add("diagnostics: missing golden $goldenPath")
        return [pscustomobject]@{ Pass = $false; Issues = $issues }
    }

    $golden = @{}
    $goldenOrder = [System.Collections.Generic.List[string]]::new()
    foreach ($row in (Read-Tsv -Path $goldenPath).Rows) {
        $golden[$row[0]] = $row[1]
        $goldenOrder.Add($row[0])
    }

    $fresh = @{}
    foreach ($r in (Get-DiagnosticsMetrics -HtmlPath $HtmlPath).Rows) { $fresh[$r[0]] = $r[1] }

    foreach ($name in $goldenOrder) {
        if (-not $fresh.ContainsKey($name)) { $issues.Add("diagnostics: metric missing from run: $name"); continue }
        $g = $golden[$name]; $f = $fresh[$name]
        if ($NoTrainedModel -and $name -eq $modelMetric) {
            # Pinned, not skipped. A run that adopted its q-values from the 1st-pass
            # sidecars trained no model, so it has no feature contributions to report
            # and this must read 0. Anything else means the report claims a feature
            # view it cannot have computed, which is the direction that would matter.
            if ($f -ne '0') {
                # Double parens: -f binds TIGHTER than the ',' separating method arguments,
                # so Add(("...") -f $name, $f) parses as a TWO-argument call and the format
                # operator throws on the missing {1}. Every other Add in this file does the
                # same. Getting it wrong is invisible until the branch first fires - which
                # here is the failure path this pin exists to report.
                $issues.Add((("diagnostics: {0} run='{1}', expected '0' - this run adopted " +
                    "first-pass q-values from the sidecars and trained no model, so it has " +
                    "no feature contributions to report") -f $name, $f))
            }
            continue
        }
        $gd = 0.0; $fd = 0.0
        # Invariant, matching how Format-CellValue WROTE these. The current-culture
        # overload reads its own invariant output wrong on a comma-decimal agent, and
        # it fails GREEN, which is the direction that matters here: under de-DE the
        # '.' is a group separator, so a tilt moving 0.236 -> 2.36 parses as 236 on
        # both sides and reports diff=0. A 10x calibration regression - exactly the
        # failure class this tier exists to catch - would pass silently.
        $inv = [System.Globalization.CultureInfo]::InvariantCulture
        $style = [System.Globalization.NumberStyles]::Float
        $bothNumeric = [double]::TryParse($g, $style, $inv, [ref]$gd) -and
                       [double]::TryParse($f, $style, $inv, [ref]$fd)
        if ($bothNumeric) {
            # NaN and +/-Infinity BOTH parse successfully here, and every comparison against
            # NaN is $false - so a bare Abs(diff) -gt Tolerance passes golden='NaN' against
            # run='4.37' silently, and the string fallback below is unreachable once TryParse
            # has succeeded. NaN is a meaningful VALUE for these metrics (a class under
            # MIN_N_FOR_ENRICHMENT reports it), so a class crossing that threshold in either
            # direction is exactly the change worth catching. Compare non-finite values for
            # equality; only finite pairs get the tolerance.
            if (-not ([double]::IsFinite($gd) -and [double]::IsFinite($fd))) {
                if ($g -ne $f) {
                    $issues.Add(("diagnostics: {0} golden='{1}' run='{2}'" -f $name, $g, $f))
                }
            } else {
                $diff = [math]::Abs($gd - $fd)
                if ($diff -gt $Tolerance) {
                    $issues.Add(("diagnostics: {0} golden={1} run={2} diff={3:e3} (tol {4:e0})" -f $name, $g, $f, $diff, $Tolerance))
                }
            }
        } elseif ($g -ne $f) {
            $issues.Add(("diagnostics: {0} golden='{1}' run='{2}'" -f $name, $g, $f))
        }
    }
    foreach ($name in $fresh.Keys) {
        if (-not $golden.ContainsKey($name)) { $issues.Add("diagnostics: metric not in golden (regenerate?): $name") }
    }

    return [pscustomobject]@{ Pass = ($issues.Count -eq 0); Issues = $issues }
}

function Test-DiagnosticsSanity {
    <#
    Tier 2: absolute correctness bounds that -CreateGolden does NOT regenerate.

    These are the guard against a regression being baptised into a regenerated
    golden. They are deliberately loose -- wide enough that ordinary, intended
    algorithm work does not trip them, tight enough that a calibration failure
    of the size we have actually shipped does. For scale: the b<->y swap put
    Stellar Pass-1 FDP at 11.81% against a claimed 1%, and its entrapment coin
    at 0.2051 against a fair 0.5. Both would blow through these by a mile.

    Reference measurements (see the gendecoy TODO): library decoys reach
    Pass-1 FDP 0.86-1.47% with a coin of ~0.5016 on Stellar 3-file, and 0.92% /
    0.5003 / tilt -0.0065 on the 82-file set. Generated decoys with the swap
    removed land near 1.47% (Stellar) and 2.03% (Astral).

    Bounds apply only where the underlying metric exists: a dataset without
    entrapment has no FDP or entrapment coin, and is checked on the
    entrapment-independent metrics only.
    #>
    param([Parameter(Mandatory = $true)][string]$HtmlPath,
          [double]$MaxPass1Fdp = 0.02,
          [double]$CoinTolerance = 0.05,
          [double]$MaxAbsTilt = 1.0)

    $issues = [System.Collections.Generic.List[string]]::new()
    $d = Get-DiagnosticsPayload -HtmlPath $HtmlPath

    # Every bound below FAILS CLOSED. PowerShell coerces a missing property to 0.0
    # ([double]$null -eq 0.0) and there is no StrictMode here, so a renamed or renested
    # JSON field would otherwise sail through every comparison and this tier -- the one
    # that -CreateGolden cannot regenerate -- would report PASS forever having evaluated
    # nothing. NaN is the same trap and is a DOCUMENTED value of this payload
    # (ModelDiagnosticsHtml serializes it as the string "NaN"): every comparison against
    # NaN is false, so NaN passes a ceiling silently. Require a real finite number.
    # Invariant, for the same reason the tier-1 comparer is: a PowerShell [string]
    # cast renders a double invariantly ('0.244'), but the current-culture TryParse
    # then reads that on a de-DE agent as 244, so EVERY bound here would blow its
    # ceiling and the sanity tier would fail every healthy run. Measured, not feared.
    function Test-Finite([string]$name, $raw, [ref]$outValue) {
        $v = 0.0
        $inv = [System.Globalization.CultureInfo]::InvariantCulture
        $style = [System.Globalization.NumberStyles]::Float
        if ($null -eq $raw -or -not [double]::TryParse([string]$raw, $style, $inv, [ref]$v) -or
            [double]::IsNaN($v) -or [double]::IsInfinity($v)) {
            $issues.Add(("SANITY: metric '{0}' is missing or non-finite ('{1}') -- the bound could not be evaluated, so it is treated as a failure rather than a pass" -f $name, $raw))
            return $false
        }
        $outValue.Value = $v
        return $true
    }

    $tilt = 0.0
    if (Test-Finite 'densityRatio.flatnessSlope' $d.densityRatio.flatnessSlope ([ref]$tilt)) {
        if ([math]::Abs($tilt) -gt $MaxAbsTilt) {
            $issues.Add(("SANITY: null-alignment tilt {0:N3} exceeds +/-{1:N2}; the decoy null no longer tracks the target-false null" -f $tilt, $MaxAbsTilt))
        }
    }

    if ($d.winFraction.hasEntrapment) {
        $coin = 0.0
        if (Test-Finite 'winFraction.nullBandEnt' $d.winFraction.nullBandEnt ([ref]$coin)) {
            if ([math]::Abs($coin - 0.5) -gt $CoinTolerance) {
                $issues.Add(("SANITY: entrapment paired-win fraction {0:N4} is more than {1:N2} from a fair 0.5; decoys are not exchangeable with false targets" -f $coin, $CoinTolerance))
            }
        }
    }

    # An entrapment pool with no usable FDP curve is a failure, not a skip: "nothing
    # reached a reported 1% q" is exactly the catastrophic-calibration case this bound
    # exists to catch, and silently skipping it would report PASS at the worst moment.
    # Datasets without entrapment have no curve by construction and are exempt.
    if ($d.hasEntrapment) {
        $fdp = Get-FdpAtThreshold -Payload $d -Pass 1 -Scope 'experiment'
        if ($null -eq $fdp) {
            $issues.Add(("SANITY: dataset has entrapment but no Pass-1 experiment FDP point at q <= {0:P2}; the calibration curve is missing or never reaches the threshold" -f $script:DiagQThreshold))
        } else {
            $combined = 0.0
            if (Test-Finite 'pass1.experiment.combinedFdp' $fdp.Combined ([ref]$combined)) {
                if ($combined -gt $MaxPass1Fdp) {
                    $issues.Add(("SANITY: Pass-1 true FDP {0:P2} at a reported q of {1:P2} exceeds the {2:P2} ceiling; reported q-values are anti-conservative" -f $combined, $fdp.Q, $MaxPass1Fdp))
                }
            }
        }
    }

    return [pscustomobject]@{ Pass = ($issues.Count -eq 0); Issues = $issues }
}
