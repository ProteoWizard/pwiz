namespace pwiz.Common.Controls
{
    /// <summary>
    /// Loads the per-DPI icons generated by Executables/DevTools/IconBuilder. Each assembly
    /// that shows small icons keeps its 16 px natives in Properties/Resources.resx and the
    /// pre-rendered sizes embedded as Resources/Icons/Name.Size.png (20, 24 and 32 for 16 px
    /// icons; 18, 21 and 28 for 14 px ones), so an icon is identified by the assembly's
    /// Resources class and the native's name. Skyline wraps this for its own resources in
    /// DpiUtil; pwiz.Common calls it directly (issue #4599).
    /// </summary>
    public static class DpiIcons
    {
        private const int ICON_NATIVE = 16;
        private const int ICON_NATIVE_SMALL = 14;
        private const string ICON_RESOURCE_SUFFIX = ".Resources.Icons.{0}.{1}.png";
        private const string RESOURCES_SUFFIX = ".Properties.Resources.resources";
        private static readonly int[] ICON_SIZES = { 20, 24, 32 };
        private static readonly int[] ICON_SIZES_SMALL = { 18, 21, 28 };

        // Images this class produced for the display DPI, so a second PrepareIcons pass over
        // the same controls (a control prepared in its constructor, then again by the form that
        // hosts it) leaves them as they are instead of scaling them a second time
        private static readonly ConditionalWeakTable<Image, object> _prepared =
            new ConditionalWeakTable<Image, object>();

        /// <summary>
        /// Returns an icon at the pixel size the control's DPI calls for: the smallest
        /// embedded size at or above the target, resampled down when they differ, or the
        /// native bitmap resampled as <see cref="DpiScale.ScaleImage"/> does when none is
        /// embedded. At 100% the native bitmap is returned untouched; otherwise it is
        /// disposed, since the caller keeps only the result. Pass the assembly's Resources
        /// class and <c>nameof(Resources.X)</c>.
        /// </summary>
        public static Image GetIcon(Type resourcesType, Control control, string name, Image native,
            Color? transparentKey = null)
        {
            if (!DpiScale.IsScaled(control))
                return native;
            var icon = LoadOrResample(resourcesType, control, name, native, transparentKey);
            native.Dispose();
            return icon;
        }

        /// <summary>
        /// The pre-rendered pixel sizes IconBuilder emits for a native icon size, in
        /// ascending order: 125%, 150% and 200%.
        /// </summary>
        public static int[] GetIconSizes(int nativeSize)
        {
            return nativeSize == ICON_NATIVE_SMALL ? ICON_SIZES_SMALL : ICON_SIZES;
        }

        /// <summary>
        /// The manifest resource name of an embedded icon file in the assembly of the given
        /// Resources class, or null when none is embedded.
        /// </summary>
        public static string GetIconResourceName(Type resourcesType, string name, int size)
        {
            return IconSource.ForResources(resourcesType).GetResourceName(name, size);
        }

        /// <summary>
        /// The Resources.resx name of a small icon bitmap of the given Resources class,
        /// matched by pixel content, or null for an image that is not one (a designer image
        /// carries no name). The transparent key is the one the image's owner applied to it:
        /// a ToolStripItem makes its ImageTransparentColor transparent in the bitmap it is
        /// given, so the natives are keyed the same way before they are compared. Two names
        /// with the same pixels resolve to the first in ordinal order.
        /// </summary>
        public static string GetIconName(Type resourcesType, Image image, Color transparentKey = default)
        {
            if (image.Width > ICON_NATIVE || image.Height > ICON_NATIVE)
                return null;
            return IconSource.ForResources(resourcesType).GetNativeName(image, transparentKey);
        }

        /// <summary>
        /// Routes the designer images under a control through <see cref="GetIcon"/>: the items
        /// of its tool strips, menus and context menus, and the images of its buttons and
        /// picture boxes. Designers assign Resources.X directly and an Image carries no
        /// resource name, so each image is matched by pixel content against the small bitmaps
        /// of Resources.resx (see <see cref="GetIconName"/>): first those of the assembly that
        /// defines the control (or, for a framework control, its nearest ancestor), then those
        /// of every other assembly met so far, so an icon two assemblies both carry takes the
        /// owner's drawing. A button's ImageList is scaled as a whole; an image shared by
        /// several controls is replaced once and shared again. Called when a form loads; a
        /// context menu that is not attached to a control, or a control created later, goes
        /// through <see cref="PrepareIcons(ToolStrip, Type)"/> or this method itself. No-op at
        /// 100%, where the natives are right as they are.
        /// </summary>
        public static void PrepareIcons(Control root)
        {
            if (!DpiScale.IsScaled(root))
                return;
            var replaced = new Dictionary<Image, Image>();
            var scaledLists = new HashSet<ImageList>();
            var pending = new Stack<Control>();
            pending.Push(root);
            while (pending.Count > 0)
            {
                var control = pending.Pop();
                var owner = IconSource.ForOwner(control);
                foreach (Control child in control.Controls)
                    pending.Push(child);
                if (control.ContextMenuStrip != null)
                    PrepareIcons(control.ContextMenuStrip.Items, control, owner, replaced);
                if (control is ToolStrip strip)
                    PrepareIcons(strip.Items, strip, owner, replaced);
                else if (control is PictureBox pictureBox)
                    pictureBox.Image = ReplaceIcon(pictureBox, owner, pictureBox.Image, replaced, false);
                else if (control.GetType() == typeof(Button))
                {
                    // Exact type only: Button subclasses (e.g. LiteDropDownList) manage their own images.
                    // WinForms leaves a Button's Image at its 96-DPI size, so an unmatched one is resampled.
                    var button = (Button) control;
                    if (button.ImageList == null)
                        button.Image = ReplaceIcon(button, owner, button.Image, replaced, true);
                    else if (scaledLists.Add(button.ImageList))
                        ImageListScaler.ScaleToDpi(button, button.ImageList);
                }
            }
        }

        /// <summary>
        /// <see cref="PrepareIcons(Control)"/> for a tool strip or context menu that no form's
        /// control tree reaches, e.g. a menu a component shows on its own. Such a strip has no
        /// parent to tell its owner from, so the Resources class of the assembly whose
        /// designer assigned the images is passed in.
        /// </summary>
        public static void PrepareIcons(ToolStrip strip, Type resourcesType = null)
        {
            if (!DpiScale.IsScaled(strip))
                return;
            var owner = resourcesType != null ? IconSource.ForResources(resourcesType) : IconSource.ForOwner(strip);
            PrepareIcons(strip.Items, strip, owner, new Dictionary<Image, Image>());
        }

        private static void PrepareIcons(ToolStripItemCollection items, Control control, IconSource owner,
            Dictionary<Image, Image> replaced)
        {
            foreach (ToolStripItem item in items)
            {
                // HasDropDownItems first: reading DropDownItems creates an empty drop-down for a leaf
                if (item is ToolStripDropDownItem dropDown && dropDown.HasDropDownItems)
                    PrepareIcons(dropDown.DropDownItems, control, owner, replaced);
                // An item drawn from its strip's ImageList by index or key is left to the list
                if (item.ImageIndex >= 0 || !string.IsNullOrEmpty(item.ImageKey))
                    continue;
                item.Image = ReplaceIcon(control, owner, item.Image, replaced, false, item.ImageTransparentColor);
            }
        }

        /// <summary>
        /// The image to show for a 96-DPI designer image at the control's DPI: the embedded
        /// icon for a Resources.resx native of any known assembly, the bicubic resample for
        /// anything else when asked for, otherwise the image itself. An image already prepared
        /// for the display DPI is returned as it is. The original is never disposed: other code
        /// may still hold it, e.g. to copy between items or to restore later.
        /// </summary>
        private static Image ReplaceIcon(Control control, IconSource owner, Image image,
            Dictionary<Image, Image> replaced, bool resampleUnknown, Color transparentKey = default)
        {
            if (image == null || _prepared.TryGetValue(image, out _))
                return image;
            if (replaced.TryGetValue(image, out var result))
                return result;
            var source = IconSource.FindNative(image, transparentKey, owner, out var name);
            if (source != null)
                result = LoadOrResample(source.ResourcesType, control, name, image, null);
            else if (resampleUnknown)
                result = MarkPrepared(DpiScale.Resample(image, DpiScale.ScaleSize(control, image.Size)));
            else
                result = image;
            replaced.Add(image, result);
            return result;
        }

        /// <summary>
        /// The embedded icon at the size the control's DPI calls for, or the native resampled
        /// to it when none is embedded. The native is left for the caller to dispose or keep.
        /// </summary>
        private static Image LoadOrResample(Type resourcesType, Control control, string name, Image native,
            Color? transparentKey)
        {
            var target = DpiScale.ScaleSize(control, native.Size);
            var icon = IconSource.ForResources(resourcesType).LoadIcon(name, native.Width, target);
            return MarkPrepared(icon ?? DpiScale.Resample(native, target, transparentKey));
        }

        private static Image MarkPrepared(Image image)
        {
            _prepared.AddOrUpdate(image, null);
            return image;
        }

        /// <summary>
        /// One assembly's icons: its Properties.Resources natives, keyed by pixel content on
        /// first use, and its embedded per-DPI files. Created from the Resources class when a
        /// caller names it, or from an assembly PrepareIcons meets, whose Resources class is
        /// found through the .resources file the designer embeds next to it.
        /// </summary>
        private sealed class IconSource
        {
            private static readonly Dictionary<Assembly, IconSource> _byAssembly =
                new Dictionary<Assembly, IconSource>();
            private static readonly List<IconSource> _sources = new List<IconSource>();
            // Guards the caches above and each source's tables: forms can load on more than one UI thread
            private static readonly object LOCK = new object();

            private readonly Assembly _assembly;
            private readonly ResourceManager _resources;
            private readonly string[] _resourceNames;
            private readonly Dictionary<int, Dictionary<string, string>> _nativeNames =
                new Dictionary<int, Dictionary<string, string>>();
            private List<KeyValuePair<string, Bitmap>> _smallNatives;

            private IconSource(Assembly assembly, Type resourcesType)
            {
                _assembly = assembly;
                ResourcesType = resourcesType;
                _resourceNames = assembly.GetManifestResourceNames();
                if (resourcesType != null)
                    _resources = new ResourceManager(resourcesType.FullName, assembly);
            }

            public Type ResourcesType { get; }

            public static IconSource ForResources(Type resourcesType)
            {
                return ForAssembly(resourcesType.Assembly, resourcesType);
            }

            /// <summary>
            /// The source for an assembly, created on first sight. Without a Resources class
            /// given, the one the designer generated is found by its embedded .resources file;
            /// an assembly without one (System.Windows.Forms, for instance) gets a source
            /// that matches nothing.
            /// </summary>
            public static IconSource ForAssembly(Assembly assembly, Type resourcesType = null)
            {
                lock (LOCK)
                {
                    if (_byAssembly.TryGetValue(assembly, out var source))
                        return source;
                    if (resourcesType == null)
                    {
                        var resourcesName = assembly.GetManifestResourceNames()
                            .FirstOrDefault(n => n.EndsWith(RESOURCES_SUFFIX, StringComparison.Ordinal));
                        if (resourcesName != null)
                        {
                            var typeName = resourcesName.Substring(0, resourcesName.Length - @".resources".Length);
                            resourcesType = assembly.GetType(typeName);
                        }
                    }
                    source = new IconSource(assembly, resourcesType);
                    _byAssembly.Add(assembly, source);
                    _sources.Add(source);
                    return source;
                }
            }

            /// <summary>
            /// The source of the assembly whose designer assigned a control's images: the
            /// control's own, or for a framework control (a ToolStrip, a Button) that of the
            /// nearest ancestor defined outside System.Windows.Forms.
            /// </summary>
            public static IconSource ForOwner(Control control)
            {
                var owner = control;
                while (owner.Parent != null && owner.GetType().Assembly == typeof(Control).Assembly)
                    owner = owner.Parent;
                return ForAssembly(owner.GetType().Assembly);
            }

            /// <summary>
            /// The source and native name a small image matches - the owner's first, then any
            /// other assembly seen so far - or null.
            /// </summary>
            public static IconSource FindNative(Image image, Color transparentKey, IconSource owner, out string name)
            {
                name = null;
                if (image.Width > ICON_NATIVE || image.Height > ICON_NATIVE)
                    return null;
                var key = GetPixelKey(image, Color.Empty);
                lock (LOCK)
                {
                    if (owner != null && owner.GetNativeNames(transparentKey).TryGetValue(key, out name))
                        return owner;
                    foreach (var source in _sources)
                    {
                        if (source != owner && source.GetNativeNames(transparentKey).TryGetValue(key, out name))
                            return source;
                    }
                    return null;
                }
            }

            public string GetNativeName(Image image, Color transparentKey)
            {
                var key = GetPixelKey(image, Color.Empty);
                lock (LOCK)
                {
                    return GetNativeNames(transparentKey).TryGetValue(key, out var name) ? name : null;
                }
            }

            /// <summary>
            /// The manifest resource name of an embedded icon file, or null when none is
            /// embedded. Matched by suffix so the root namespace never has to be spelled out.
            /// </summary>
            public string GetResourceName(string name, int size)
            {
                var suffix = string.Format(CultureInfo.InvariantCulture, ICON_RESOURCE_SUFFIX, name, size);
                return _resourceNames.FirstOrDefault(n => n.EndsWith(suffix, StringComparison.Ordinal));
            }

            public Image LoadIcon(string name, int nativeSize, Size target)
            {
                // Smallest pre-rendered size at or above the target, else the largest there is
                var sizes = GetIconSizes(nativeSize);
                var size = sizes.FirstOrDefault(s => s >= target.Width);
                if (size == 0)
                    size = sizes.Last();
                var resourceName = GetResourceName(name, size);
                if (resourceName == null)
                    return null;
                using (var stream = _assembly.GetManifestResourceStream(resourceName))
                using (var loaded = new Bitmap(stream))
                {
                    if (loaded.Size == target)
                        return CopyBitmap(loaded);
                    return DpiScale.Resample(loaded, target);
                }
            }

            /// <summary>
            /// Pixel-content key to Resources.resx name for every bitmap up to 16 px, with the
            /// given transparent key applied, built on first use per key color. Called under LOCK.
            /// </summary>
            private Dictionary<string, string> GetNativeNames(Color transparentKey)
            {
                if (_nativeNames.TryGetValue(transparentKey.ToArgb(), out var names))
                    return names;
                names = new Dictionary<string, string>();
                foreach (var native in GetSmallNatives())
                {
                    var key = GetPixelKey(native.Value, transparentKey);
                    if (!names.TryGetValue(key, out var existing) || string.CompareOrdinal(native.Key, existing) < 0)
                        names[key] = native.Key;
                }
                _nativeNames[transparentKey.ToArgb()] = names;
                return names;
            }

            /// <summary>
            /// The Resources.resx bitmaps up to 16 px, decoded once and kept for keying under
            /// each transparent color. Enumerating the resource set deserializes a fresh bitmap
            /// per entry (objects are not cached the way strings are), so the larger ones are
            /// disposed right away. Called under LOCK.
            /// </summary>
            private List<KeyValuePair<string, Bitmap>> GetSmallNatives()
            {
                if (_smallNatives != null)
                    return _smallNatives;
                _smallNatives = new List<KeyValuePair<string, Bitmap>>();
                var resourceSet = _resources?.GetResourceSet(CultureInfo.InvariantCulture, true, true);
                if (resourceSet == null)
                    return _smallNatives;
                foreach (DictionaryEntry entry in resourceSet)
                {
                    if (!(entry.Value is Bitmap bitmap))
                        continue;
                    if (bitmap.Width > ICON_NATIVE || bitmap.Height > ICON_NATIVE)
                        bitmap.Dispose();
                    else
                        _smallNatives.Add(new KeyValuePair<string, Bitmap>((string) entry.Key, bitmap));
                }
                return _smallNatives;
            }

            /// <summary>
            /// The image's size and 32-bit ARGB pixels as a string, after the transparent key
            /// (if any) is made transparent the way ToolStripItem does it, so bitmaps decoded
            /// from the same resource bytes compare equal whatever their pixel format. Every
            /// fully transparent pixel reads as zero, whatever color it carries.
            /// </summary>
            private static string GetPixelKey(Image image, Color transparentKey)
            {
                using (var bitmap = new Bitmap(image.Width, image.Height, PixelFormat.Format32bppArgb))
                {
                    using (var g = Graphics.FromImage(bitmap))
                    {
                        g.CompositingMode = CompositingMode.SourceCopy;
                        g.DrawImage(image, new Rectangle(Point.Empty, image.Size),
                            new Rectangle(Point.Empty, image.Size), GraphicsUnit.Pixel);
                    }
                    if (transparentKey != Color.Empty)
                        bitmap.MakeTransparent(transparentKey);
                    var data = bitmap.LockBits(new Rectangle(Point.Empty, bitmap.Size), ImageLockMode.ReadOnly,
                        PixelFormat.Format32bppArgb);
                    try
                    {
                        var bytes = new byte[data.Stride * data.Height];
                        Marshal.Copy(data.Scan0, bytes, 0, bytes.Length);
                        for (var i = 0; i < bytes.Length; i += 4)
                        {
                            if (bytes[i + 3] == 0)   // B, G, R, A
                                bytes[i] = bytes[i + 1] = bytes[i + 2] = 0;
                        }
                        return string.Format(CultureInfo.InvariantCulture, @"{0}x{1}:{2}",
                            image.Width, image.Height, Convert.ToBase64String(bytes));
                    }
                    finally
                    {
                        bitmap.UnlockBits(data);
                    }
                }
            }

            /// <summary>
            /// Pixel-exact copy into a 96-DPI 32-bit ARGB bitmap that does not depend on the
            /// stream the original was decoded from.
            /// </summary>
            private static Bitmap CopyBitmap(Bitmap source)
            {
                var copy = new Bitmap(source.Width, source.Height, PixelFormat.Format32bppArgb);
                copy.SetResolution(DpiScale.REFERENCE_DPI, DpiScale.REFERENCE_DPI);
                using (var g = Graphics.FromImage(copy))
                {
                    g.DrawImage(source, new Rectangle(Point.Empty, source.Size),
                        new Rectangle(Point.Empty, source.Size), GraphicsUnit.Pixel);
                }
                return copy;
            }
        }
    }
